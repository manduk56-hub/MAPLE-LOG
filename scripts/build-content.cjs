'use strict';
const fs = require('node:fs');
const path = require('node:path');
  function validate(data) {
    const name = (value, max) => typeof value === 'string' && value.trim() === value && value.length > 0 && value.length <= max;
    if (!data || data.schemaVersion !== 1 || !Number.isSafeInteger(data.version) || data.version < 1 ||
        typeof data.updatedAt !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(data.updatedAt) ||
        !Array.isArray(data.bosses) || !data.bosses.length || data.bosses.length > 500 ||
        !Array.isArray(data.items) || data.items.length > 5000) throw new Error('format');
    const date = new Date(`${data.updatedAt}T00:00:00Z`);
    if (isNaN(date) || date.toISOString().slice(0, 10) !== data.updatedAt) throw new Error('date');
    const names = new Set();
    for (const entry of data.bosses) {
      if (!Array.isArray(entry) || entry.length !== 2) throw new Error('boss');
      const [boss, difficulties] = entry;
      if (!name(boss, 50) || boss === 'custom' || names.has(boss) || !Array.isArray(difficulties) ||
          !difficulties.length || difficulties.length > 20 || !difficulties.every(d => name(d, 20)) ||
          new Set(difficulties).size !== difficulties.length) throw new Error('boss');
      names.add(boss);
    }
    if (!data.items.every(item => name(item, 100)) || new Set(data.items).size !== data.items.length) throw new Error('items');
    return { schemaVersion: 1, version: data.version, updatedAt: data.updatedAt,
      bosses: data.bosses.map(([boss, difficulties]) => [boss, [...difficulties]]), items: [...data.items] };
  }

function generate(catalog) {
  const data = JSON.stringify(validate(catalog));
  return "// Generated by scripts/build-content.cjs from content/catalog.json.\n'use strict';\n(function (root) {\n  const catalog = " + data + ";\n  if (typeof module === 'object' && module.exports) module.exports = { catalog };\n  else root.MapleContent = { catalog };\n})(globalThis);\n";
}
if (require.main === module) {
  const root = path.join(__dirname, '..');
  const output = generate(JSON.parse(fs.readFileSync(path.join(root, 'content/catalog.json'), 'utf8')));
  const target = path.join(root, 'content.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('content.js is outdated. Run npm run content:build.');
  } else fs.writeFileSync(target, output);
}
module.exports = { validate, generate };
